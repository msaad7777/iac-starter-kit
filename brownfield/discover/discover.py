"""Write Terraform import blocks for resources that exist but are not managed yet.

Read-only: it only calls List/Describe APIs. Works against Moto or, with read-only
credentials, a real account. Default VPCs and default security groups are skipped
because nobody created them on purpose.

    python discover.py --out imports.tf [--skip-bucket NAME ...]
"""
import argparse
import re

import boto3


def tf_name(raw: str) -> str:
    name = re.sub(r"[^a-zA-Z0-9_]", "_", raw).strip("_").lower()
    return name if name[:1].isalpha() else f"r_{name}"


def tag(tags, key):
    return next((t["Value"] for t in tags or [] if t["Key"] == key), None)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="imports.tf")
    p.add_argument("--skip-bucket", action="append", default=[], help="Buckets already managed elsewhere")
    args = p.parse_args()

    s3, ec2 = boto3.client("s3"), boto3.client("ec2")
    blocks = []

    for b in s3.list_buckets()["Buckets"]:
        if b["Name"] in args.skip_bucket:
            continue
        blocks.append(("aws_s3_bucket", tf_name(b["Name"]), b["Name"]))

    default_vpcs = set()
    for v in ec2.describe_vpcs()["Vpcs"]:
        if v.get("IsDefault"):
            default_vpcs.add(v["VpcId"])
            continue
        blocks.append(("aws_vpc", tf_name(tag(v.get("Tags"), "Name") or v["VpcId"]), v["VpcId"]))

    for s in ec2.describe_subnets()["Subnets"]:
        if s["VpcId"] in default_vpcs:
            continue
        blocks.append(("aws_subnet", tf_name(tag(s.get("Tags"), "Name") or s["SubnetId"]), s["SubnetId"]))

    for g in ec2.describe_security_groups()["SecurityGroups"]:
        if g["VpcId"] in default_vpcs or g["GroupName"] == "default":
            continue
        blocks.append(("aws_security_group", tf_name(g["GroupName"]), g["GroupId"]))

    with open(args.out, "w") as f:
        f.write("# Generated by discover.py. Review before planning.\n")
        for rtype, name, rid in blocks:
            f.write(f'\nimport {{\n  to = {rtype}.{name}\n  id = "{rid}"\n}}\n')
    print(f"wrote {len(blocks)} import blocks to {args.out}")


if __name__ == "__main__":
    main()
